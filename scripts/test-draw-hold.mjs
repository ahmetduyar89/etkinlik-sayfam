import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
const dir = await mkdtemp(join(tmpdir(), 'draw-hold-'));
try {
    const outfile = join(dir, 'engine.mjs');
    await build({ stdin: { contents: "export * from './src/components/drawing/engine/recognition'; export * from './src/components/drawing/engine/geometry'; export * from './src/components/drawing/engine/DrawHold'; export * from './src/components/drawing/engine/inking'; export * from './src/components/drawing/engine/adapter'; export {encodePages,decodePages} from './src/components/notebooks/pageCodec';", resolveDir: process.cwd() }, bundle: true, platform: 'node', format: 'esm', outfile });
    const { GeometricShapeRecognizer, simplifyRDP, transformShape, DrawHoldController, HOLD_DELAY_MS, brushOutline, shapeToStroke, shapePath, encodePages, decodePages } = await import(pathToFileURL(outfile));
    const recognizer = new GeometricShapeRecognizer();
    assert.equal(recognizer.recognize([{x:0,y:0},{x:100,y:0}])?.kind, 'line', 'sparse input line');
    const segment = (a, b, n = 20) => Array.from({ length: n }, (_, i) => ({ x: a.x + (b.x - a.x) * i / (n - 1), y: a.y + (b.y - a.y) * i / (n - 1) }));
    const polygon = vertices => vertices.flatMap((a, i) => segment(a, vertices[(i + 1) % vertices.length]));
    const rotate = (points, a) => points.map(p => ({ x: p.x * Math.cos(a) - p.y * Math.sin(a), y: p.x * Math.sin(a) + p.y * Math.cos(a) }));
    const circle = Array.from({ length: 121 }, (_, i) => ({ x: 120 + 70 * Math.cos(i * Math.PI / 60), y: 150 + 70 * Math.sin(i * Math.PI / 60) }));
    const ellipse = rotate(circle.map(p => ({ x: p.x * 2, y: p.y })), .7);
    const rect = polygon([{ x: 0, y: 0 }, { x: 120, y: 0 }, { x: 120, y: 70 }, { x: 0, y: 70 }]);
    const triangle = polygon([{ x: 0, y: 0 }, { x: 120, y: 80 }, { x: 10, y: 100 }]);
    const arrow = [ ...segment({ x: 0, y: 0 }, { x: 160, y: 0 }), ...segment({ x: 160, y: 0 }, { x: 130, y: -20 }), ...segment({ x: 130, y: -20 }, { x: 160, y: 0 }), ...segment({ x: 160, y: 0 }, { x: 130, y: 20 }) ];
    const cases = [[segment({ x: 0, y: 0 }, { x: 120, y: 6 }), 'line'], [circle, 'circle'], [ellipse, 'ellipse'], [rect, 'polygon'], [rotate(rect, .8), 'polygon'], [triangle, 'polygon'], [arrow, 'arrow']];
    for (const [points, kind] of cases) {
        assert.equal(recognizer.recognize(points)?.kind, kind, kind);
        for (const scale of [.25, 1, 4]) assert.equal(recognizer.recognize(points.map(p => ({ x: p.x / scale, y: p.y / scale })), scale)?.kind, kind, `${kind}: zoom ${scale}`);
    }
    const rotatedEllipse = recognizer.recognize(ellipse);
    assert.ok(Math.abs(rotatedEllipse.rotation - .7) < .02);
    assert.ok(Math.abs(rotatedEllipse.radiusX - 140) < 2);
    assert.ok(Math.abs(rotatedEllipse.radiusY - 70) < 2);
    assert.equal(recognizer.recognize([{ x: NaN, y: 0 }, ...circle]), null);
    assert.equal(recognizer.recognize(circle, 0), null);
    assert.equal(recognizer.recognize(circle.map(p => ({ x: p.x * .1, y: p.y * .1 }))), null);
    assert.equal(recognizer.recognize(circle.slice(0, 70)), null, 'partial circle rejected');
    assert.equal(recognizer.recognize(segment({ x: 0, y: 0 }, { x: 0, y: 0 })), null);
    assert.equal(recognizer.recognize([...segment({ x: 0, y: 0 }, { x: 160, y: 0 }), ...segment({ x: 160, y: 0 }, { x: 130, y: -20 })]), null, 'one hook is not an arrow');
    const line = recognizer.recognize(cases[0][0]);
    assert.ok(Math.abs(line.end.y) < 1e-6, '5 degree angle snap');
    assert.equal(simplifyRDP(segment({ x: 0, y: 0 }, { x: 200, y: 0 }, 10000)).length, 2);
    const outside = { x: -5, y: 0 };
    assert.equal(simplifyRDP([{ x: 0, y: 0 }, outside, { x: 10, y: 0 }], 3).length, 3, 'RDP measures segments, not infinite lines');
    for (const [raw] of cases) {
        const shape = recognizer.recognize(raw);
        const transformed = transformShape(shape, { x: 0, y: 0 }, { x: 100, y: 0 }, { x: 0, y: 200 });
        assert.ok(transformed);
        assert.deepEqual(transformShape(shape, { x: 0, y: 0 }, { x: 100, y: 0 }, { x: 100, y: 0 }), shape, 'no jump at hold origin');
        const stroke = { id: 'shape', color: '#ff0', width: 3, shapeInk: 'highlighter', ...shapeToStroke(transformed) };
        const decoded = decodePages(encodePages([{ strokes: [stroke], boxes: [] }]))[0].strokes[0];
        assert.equal(decoded.tool, stroke.tool); assert.equal(decoded.shapeInk, stroke.shapeInk);
        assert.equal(decoded.rotation, stroke.rotation); assert.equal(decoded.arrowHeadAngle, stroke.arrowHeadAngle);
        decoded.points.forEach((p, i) => assert.ok(Math.hypot(p.x - stroke.points[i].x, p.y - stroke.points[i].y) < .071, 'codec preserves subpixel geometry'));
    }
    // Deterministic timer tests: no wall-clock sleeps or browser dependency.
    let scheduled = new Map(), id = 0, lastCallback, delay;
    const scheduler = { set(callback, ms) { delay = ms; lastCallback = callback; scheduled.set(++id, callback); return id; }, clear(id) { scheduled.delete(id); } };
    const advance = () => { const callbacks = [...scheduled.values()]; scheduled.clear(); callbacks.forEach(f => f()); };
    const output = [];
    const controller = new DrawHoldController(recognizer, scheduler);
    controller.begin(7, cases[0][0][0], cases[0][0], 1, s => output.push(s));
    assert.equal(delay, 450); assert.equal(HOLD_DELAY_MS, 450);
    controller.move(7, { x: 120, y: 6 }, cases[0][0], 1);
    const timer = id;
    controller.move(7, { x: 124, y: 8 }, cases[0][0], 1);
    assert.equal(id, timer, 'microjitter keeps timer');
    controller.move(9, { x: 500, y: 500 }, cases[0][0], 1);
    assert.equal(id, timer, 'foreign pointer ignored');
    advance(); assert.equal(controller.state, 'shaped'); assert.equal(output.length, 1);
    controller.move(7, { x: 240, y: 12 }, cases[0][0], 1);
    assert.ok(output.at(-1).end.x > 200);
    controller.end(9); assert.equal(controller.state, 'shaped');
    controller.end(7); assert.equal(controller.state, 'idle');
    controller.begin(7, { x: 0, y: 0 }, circle, 1, s => output.push(s));
    const stale = lastCallback;
    controller.cancel(); stale(); assert.equal(controller.state, 'idle');
    const before = output.length;
    controller.begin(8, { x: 0, y: 0 }, circle, 1, s => output.push(s)); stale();
    assert.equal(output.length, before, 'stale timer cannot morph new stroke');
    controller.cancel(); advance(); assert.equal(output.length, before);
    controller.begin(7, { x: 0, y: 0 }, [], 1, s => output.push(s)); advance();
    assert.equal(controller.state, 'drawing', 'failed recognition leaves handwriting');
    controller.move(7, { x: 20, y: 0 }, circle, 1); advance();
    assert.equal(controller.state, 'shaped', 'movement rearms failed recognition'); controller.cancel();
    const settings = { type: 'pen', color: '#000', baseWidth: 4, minWidth: .8, maxWidth: 10, pressureSensitivity: 1, smoothingFactor: .4 };
    const samples = pressure => segment({ x: 0, y: 0 }, { x: 120, y: 0 }).map((p, i) => ({ ...p, pressure, timestamp: i * 10 }));
    const height = outline => Math.max(...outline.map(p => p.y)) - Math.min(...outline.map(p => p.y));
    assert.ok(height(brushOutline(samples(.9), settings, 'brush')) > height(brushOutline(samples(.1), settings, 'brush')));
    assert.ok(height(brushOutline(samples(.7), settings, 'brush').filter(p => p.x > 40 && p.x < 80)) > height(brushOutline(samples(.7).map(p => ({ ...p, timestamp: p.timestamp / 5 })), settings, 'brush').filter(p => p.x > 40 && p.x < 80)), 'speed response');
    assert.ok(height(brushOutline(samples(1), settings, 'brush')) <= settings.maxWidth);
    assert.ok(brushOutline(samples(.5), settings).every(p => Number.isFinite(p.x) && Number.isFinite(p.y)));
    assert.throws(() => brushOutline(samples(.5), { ...settings, minWidth: -1 }), RangeError);
    assert.equal(height(brushOutline(samples(.9), { ...settings, type: 'highlighter' })), 4, 'highlighter is constant width');
    globalThis.Path2D = class { calls = []; moveTo(...a) { this.calls.push(['M', ...a]); } lineTo(...a) { this.calls.push(['L', ...a]); } arc(...a) { this.calls.push(['A', ...a]); } ellipse(...a) { this.calls.push(['E', ...a]); } closePath() { this.calls.push(['Z']); } };
    assert.ok(shapePath(rotatedEllipse).calls.some(c => c[0] === 'E'));
    assert.equal(shapePath(recognizer.recognize(rect)).calls.at(-1)[0], 'Z');
    console.log('Draw & Hold: 7 geometric cases at 3 zoom levels, rotation, rejection, iterative RDP, pointer ownership, stale timers, transforms, persistence, brush width/speed and vector paths passed.');
} finally { await rm(dir, { recursive: true, force: true }); }
